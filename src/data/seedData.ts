function makeRecord(params: {
  subjectId: string;
  subjectCode: string;
  subjectName: string;
  subjectType: 'Theory' | 'Practical';
  credits: number;
  workingDays: number;
  present: number;
  ia1: number;
  ia2: number;
  ia3: number;
  assignmentMarks: number;
  practicalMarks?: number;
  classParticipation: number;
  assignments: AssignmentEntry[];
}): StudentSubjectRecord {
  return computeSubjectRecordMetrics({
    subjectId: params.subjectId,
    subjectCode: params.subjectCode,
    subjectName: params.subjectName,
    subjectType: params.subjectType,
    credits: params.credits,
    totalWorkingDays: params.workingDays,
    daysPresent: params.present,
    daysAbsent: params.workingDays - params.present,
    attendancePct: 0,
    ia1: params.ia1,
    ia2: params.ia2,
    ia3: params.ia3,
    assignmentMarks: params.assignmentMarks,
    practicalMarks: params.practicalMarks ?? 0,
    internalAvg: 0,
    assignments: params.assignments,
    classParticipation: params.classParticipation,
    assignmentCompletionPct: 0,
    engagementScore: 0,
  });
}

function buildSeedStudent(
  base: Omit<
    Student,
    | 'gpa'
    | 'internalMarksAvg'
    | 'attendanceRate'
    | 'lmsEngagement'
    | 'lmsInactiveDays'
    | 'assignmentsCompleted'
    | 'assignmentsTotal'
    | 'missingAssignments'
    | 'riskScore'
    | 'riskDrivers'
    | 'subjectMarks'
  >
): Student {
  const draft: Student = {
    ...base,
    gpa: 7.5,
    internalMarksAvg: 75,
    attendanceRate: 80,
    lmsEngagement: 75,
    lmsInactiveDays: 3,
    assignmentsCompleted: 0,
    assignmentsTotal: 0,
    missingAssignments: 0,
    riskScore: 50,
    riskDrivers: [],
    subjectMarks: [],
  };
  return recalculateStudentFromSubjectRecords(draft, base.subjectRecords);
}

